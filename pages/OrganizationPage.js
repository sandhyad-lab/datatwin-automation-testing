    /**
     * Clears one mandatory field, clicks Validate and expects an error.
     * Returns 'skipped' when the field is read-only (e.g. record is Active).
     */
    async expectRequiredFieldValidation(field, options = {}) {
        const {
            errorRegex = /required|mandatory|cannot be empty|please enter|please select|must be provided|invalid/i,
            restore = true,
        } = options;

        const control = await this.control(field);

        await control
            .evaluate(el => el.scrollIntoView({ block: 'center', inline: 'nearest' }))
            .catch(() => { });

        if (!(await control.isEditable().catch(() => false))) {
            console.warn(`"${field}" is read-only on this record - skipped.`);
            return 'skipped';
        }

        const originalValue = await this.readValue(control);

        if (!originalValue) {
            throw new Error(
                `"${field}" is already empty. ` +
                'This test expects a populated value to clear and restore.'
            );
        }

        const stateOf = async () => ({
            aria: await control.getAttribute('aria-invalid').catch(() => null),
            cls: (await control.getAttribute('class').catch(() => '')) || '',
        });

        try {
            const before = await stateOf();
            await this.clearValue(control);

            const messages = this.page.getByText(errorRegex);
            const messagesBefore = await messages.count();

            // toasts, popups and inline error elements, whatever their wording
            const alerts = this.page.locator(
                '[role="alert"], [role="dialog"], [class*="toast" i], [class*="snack" i], ' +
                '[class*="notification" i], [class*="error" i], [class*="invalid" i]'
            );
            const alertsBefore = await alerts.count();
            const textBefore = await this.page.locator('body').innerText().catch(() => '');

            await this.clickValidate();

            const gotMessage = await expect
                .poll(
                    async () =>
                        (await messages.count()) > messagesBefore ||
                        (await alerts.count()) > alertsBefore,
                    { timeout: 5000 }
                )
                .toBe(true)
                .then(() => true)
                .catch(() => false);

            // text that appeared on the page after Validate (shown in the failure message)
            const textAfter = await this.page.locator('body').innerText().catch(() => '');
            const seen = new Set(textBefore.split('\n').map(l => l.trim()));
            const newText = textAfter
                .split('\n')
                .map(l => l.trim())
                .filter(l => l && !seen.has(l))
                .slice(0, 10);

            const after = await stateOf();
            const errClass = /invalid|error/i;
            const becameInvalid =
                after.aria === 'true' ||
                (errClass.test(after.cls) && !errClass.test(before.cls));

            expect(
                gotMessage || becameInvalid,
                `Expected validation for empty mandatory field "${field}", ` +
                'but no new error message or invalid state appeared after Validate. ' +
                `New text on the page after Validate: ${newText.length ? JSON.stringify(newText) : '(none)'}`
            ).toBeTruthy();

            return 'validated';
        } finally {
            if (restore) {
                const restoreOp = this.config(this.currentKey).dropdowns.includes(field)
                    ? this.selectFromDropdown(control, originalValue)
                    : this.restoreValue(control, originalValue);

                await restoreOp.catch(error => {
                    console.warn(
                        `Could not restore "${field}". Restore it manually. ${error.message}`
                    );
                });
            }
        }
    }

    async validateRequiredFields(key) {
        const config = this.config(key);
        this.currentKey = key;

        const skipped = [];

        for (const field of config.requiredFields) {
            // uploads and system-generated values cannot be cleared with fill()
            if (config.uploads.includes(field) || config.autoGenerated.includes(field)) {
                continue;
            }

            const result = await this.expectRequiredFieldValidation(field);
            if (result === 'skipped') skipped.push(field);
        }

        expect(
            skipped,
            `[${config.name}] these mandatory fields are read-only, so the clear-and-validate ` +
            'check could not run. Use a Draft / editable record.'
        ).toEqual([]);
    }

